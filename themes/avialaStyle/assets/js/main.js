console.log('This site was generated by Hugo.');
document.documentElement.classList.add('js');

const blogBackVtStorageKey = 'blogBackVtName';
const blogReturnRevealOnceStorageKey = 'blogReturnRevealOnce';

const blogReturnRevealState = {
    shouldDelayReveal: sessionStorage.getItem(blogReturnRevealOnceStorageKey) === '1' && location.pathname === '/blogs/',
    startReveal: null
};

const applyPendingBlogBackViewTransitionName = () => {
    const vtName = sessionStorage.getItem(blogBackVtStorageKey);
    if (!vtName) return false;
    const blogSection = document.querySelector('.blogSection');
    if (!blogSection) return false;

    const matching = blogSection.querySelector(`[data-vt-name="${vtName}"]`);
    if (!matching) return false;

    blogSection.classList.add('blogReturnPending');
    const keep = matching.closest('[data-blog-reveal]');
    if (keep) {
        keep.classList.add('blogReturnKeep');
    }

    const allPreviews = blogSection.querySelectorAll('.blogItemPreview[data-vt-name], .headlineImg[data-vt-name]');
    allPreviews.forEach((el) => {
        el.style.viewTransitionName = 'none';
    });
    matching.style.viewTransitionName = vtName;
    sessionStorage.removeItem(blogBackVtStorageKey);
    return true;
};

document.addEventListener('readystatechange', () => {
    if (document.readyState === 'interactive') {
        applyPendingBlogBackViewTransitionName();
    }
});

// 移动菜单交互功能
document.addEventListener('DOMContentLoaded', function() {
    // 使用更通用的选择器来找到所有可能的触发按钮
    const openMenuBtns = document.querySelectorAll('#openMobileMenuBtn, .mobile-menu-trigger a');
    const closeMenuBtn = document.getElementById('closeMobileMenuBtn');
    const mobileMenuWrapper = document.getElementById('headerMobileMenu');
    
    console.log('Mobile menu elements:', {
        openMenuBtns: openMenuBtns.length,
        closeMenuBtn,
        mobileMenuWrapper
    });
    
    // 打开移动菜单
    function openMobileMenu() {
        if (mobileMenuWrapper) {
            console.log('Opening mobile menu');
            mobileMenuWrapper.style.display = 'block';
            // 添加一点延迟来确保显示动画效果
            setTimeout(() => {
                mobileMenuWrapper.classList.add('active');
            }, 10);
        }
    }
    
    // 关闭移动菜单
    function closeMobileMenu() {
        if (mobileMenuWrapper) {
            console.log('Closing mobile menu');
            mobileMenuWrapper.classList.remove('active');
            // 等待动画完成后隐藏元素
            setTimeout(() => {
                mobileMenuWrapper.style.display = 'none';
            }, 300); // 假设动画时长为300ms
        }
    }
    
    // 绑定所有触发按钮的事件监听器
    openMenuBtns.forEach(function(btn) {
        if (btn) {
            console.log('Binding open menu button:', btn);
            btn.addEventListener('click', function(e) {
                e.preventDefault();
                console.log('Open menu button clicked');
                openMobileMenu();
            });
        }
    });
    
    if (openMenuBtns.length === 0) {
        console.log('No open menu buttons found');
    }
    
    if (closeMenuBtn) {
        console.log('Binding close menu button');
        closeMenuBtn.addEventListener('click', function(e) {
            e.preventDefault();
            console.log('Close menu button clicked');
            closeMobileMenu();
        });
    } else {
        console.log('Close menu button not found');
    }
    
    // 点击菜单外部区域关闭菜单
    if (mobileMenuWrapper) {
        mobileMenuWrapper.addEventListener('click', function(e) {
            if (e.target === mobileMenuWrapper) {
                closeMobileMenu();
            }
        });
    }
    
    // ESC键关闭菜单
    document.addEventListener('keydown', function(e) {
        if (e.key === 'Escape' && mobileMenuWrapper && mobileMenuWrapper.classList.contains('active')) {
            closeMobileMenu();
        }
    });

    const blogSection = document.querySelector('.blogSection');
    if (blogSection) {
        const didApplyBackName = applyPendingBlogBackViewTransitionName();
        const prefersReducedMotion = window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches;
        const startReveal = () => {
            const revealItems = Array.from(blogSection.querySelectorAll('[data-blog-reveal]'));
            revealItems.forEach((el, index) => {
                const delayMs = Math.min(index * 70, 700);
                el.style.setProperty('--blog-reveal-delay', `${delayMs}ms`);
            });
            requestAnimationFrame(() => {
                blogSection.classList.remove('blogReturnPending');
                blogSection.querySelectorAll('.blogReturnKeep').forEach((el) => el.classList.remove('blogReturnKeep'));
                blogSection.classList.add('blogRevealActive');
            });
        };

        if (prefersReducedMotion) {
            blogSection.classList.add('blogRevealActive');
        } else if (blogReturnRevealState.shouldDelayReveal && didApplyBackName) {
            sessionStorage.removeItem(blogReturnRevealOnceStorageKey);
            blogReturnRevealState.shouldDelayReveal = false;
            blogReturnRevealState.startReveal = startReveal;
            window.addEventListener(
                'pagereveal',
                (e) => {
                    const run = () => {
                        if (typeof blogReturnRevealState.startReveal === 'function') {
                            blogReturnRevealState.startReveal();
                        }
                    };
                    if (e && e.viewTransition && e.viewTransition.finished && typeof e.viewTransition.finished.then === 'function') {
                        e.viewTransition.finished.then(run);
                    } else {
                        setTimeout(run, 520);
                    }
                },
                { once: true }
            );
            setTimeout(() => {
                if (!blogSection.classList.contains('blogRevealActive')) {
                    startReveal();
                }
            }, 900);
        } else if (blogReturnRevealState.shouldDelayReveal && !didApplyBackName) {
            sessionStorage.removeItem(blogReturnRevealOnceStorageKey);
            blogReturnRevealState.shouldDelayReveal = false;
            startReveal();
        } else {
            startReveal();
        }
    }

    const page = document.querySelector('.page');
    if (page && location.pathname.startsWith('/blogs/') && location.pathname !== '/blogs/') {
        const prefersReducedMotion = window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches;
        if (!prefersReducedMotion) {
            requestAnimationFrame(() => {
                page.classList.add('blogArticleEnterActive');
            });
        }
    }

    const supportsNativeViewTransition =
        typeof CSS !== 'undefined' &&
        typeof CSS.supports === 'function' &&
        CSS.supports('view-transition-name: blog-preview-test') &&
        'onpagereveal' in window;

    document.querySelectorAll('[data-back-link]').forEach((el) => {
        el.addEventListener('click', (e) => {
            if (e.defaultPrevented) return;
            if (e.button !== 0) return;
            if (e.metaKey || e.ctrlKey || e.shiftKey || e.altKey) return;
            const href = el.getAttribute('href') || '/';
            const ref = document.referrer ? new URL(document.referrer, location.href) : null;

            if (supportsNativeViewTransition) {
                e.preventDefault();
                const preview = document.querySelector('.page .previewImg[data-vt-name]');
                const vtName = preview ? preview.getAttribute('data-vt-name') : null;
                if (vtName && href === '/blogs/') {
                    sessionStorage.setItem(blogBackVtStorageKey, vtName);
                    sessionStorage.setItem(blogReturnRevealOnceStorageKey, '1');
                }
                location.href = href;
                return;
            }

            if (ref && ref.origin === location.origin && history.length > 1) {
                e.preventDefault();
                history.back();
                return;
            }
            if (!href) return;
        });
    });

    const previewTransitionStorageKey = 'blogPreviewTransition';

    if (!supportsNativeViewTransition) {
        const stored = sessionStorage.getItem(previewTransitionStorageKey);
        if (stored) {
            sessionStorage.removeItem(previewTransitionStorageKey);
            try {
                const data = JSON.parse(stored);
                if (data && data.toPath === location.pathname) {
                    const target = document.querySelector('.page .previewImg');
                    const prefersReducedMotion = window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches;
                    if (target && !prefersReducedMotion) {
                        const toRect = target.getBoundingClientRect();
                        const overlay = document.createElement('div');
                        overlay.style.position = 'fixed';
                        overlay.style.left = `${data.from.left}px`;
                        overlay.style.top = `${data.from.top}px`;
                        overlay.style.width = `${data.from.width}px`;
                        overlay.style.height = `${data.from.height}px`;
                        overlay.style.backgroundImage = data.backgroundImage;
                        overlay.style.backgroundSize = 'cover';
                        overlay.style.backgroundPosition = 'center';
                        overlay.style.borderRadius = data.borderRadius;
                        overlay.style.zIndex = '9999';
                        overlay.style.pointerEvents = 'none';
                        overlay.style.willChange = 'top, left, width, height, border-radius';
                        overlay.style.transitionProperty = 'top, left, width, height, border-radius';
                        overlay.style.transitionDuration = '520ms';
                        overlay.style.transitionTimingFunction = 'cubic-bezier(0.2, 0.8, 0.2, 1)';

                        const targetBorderRadius = getComputedStyle(target).borderRadius;
                        target.style.opacity = '0';
                        document.body.appendChild(overlay);

                        requestAnimationFrame(() => {
                            overlay.style.left = `${toRect.left}px`;
                            overlay.style.top = `${toRect.top}px`;
                            overlay.style.width = `${toRect.width}px`;
                            overlay.style.height = `${toRect.height}px`;
                            overlay.style.borderRadius = targetBorderRadius;
                        });

                        const finish = () => {
                            overlay.remove();
                            target.style.opacity = '';
                        };
                        overlay.addEventListener('transitionend', finish, { once: true });
                        setTimeout(finish, 650);
                    }
                }
            } catch (_) {}
        }
    }

    if (blogSection) {
        const storePreviewTransition = (previewEl, linkEl) => {
            if (!previewEl || !linkEl) return;
            const rect = previewEl.getBoundingClientRect();
            if (!rect.width || !rect.height) return;
            const backgroundImage = getComputedStyle(previewEl).backgroundImage;
            if (!backgroundImage || backgroundImage === 'none') return;
            const borderRadius = getComputedStyle(previewEl).borderRadius;
            const toPath = new URL(linkEl.href, location.href).pathname;
            sessionStorage.setItem(
                previewTransitionStorageKey,
                JSON.stringify({
                    toPath,
                    from: { left: rect.left, top: rect.top, width: rect.width, height: rect.height },
                    backgroundImage,
                    borderRadius
                })
            );
        };

        blogSection.addEventListener('click', (e) => {
            const link = e.target && e.target.closest ? e.target.closest('a') : null;
            if (!link) return;
            if (link.target && link.target !== '_self') return;
            if (e.defaultPrevented) return;
            if (e.button !== 0) return;
            if (e.metaKey || e.ctrlKey || e.shiftKey || e.altKey) return;

            const url = new URL(link.href, location.href);
            if (url.origin !== location.origin) return;

            const preview = link.querySelector('.blogItemPreview, .headlineImg');
            if (!preview) return;
            const vtName = preview.getAttribute('data-vt-name');
            if (supportsNativeViewTransition && vtName) {
                e.preventDefault();
                const allPreviews = blogSection.querySelectorAll('.blogItemPreview[data-vt-name], .headlineImg[data-vt-name]');
                allPreviews.forEach((el) => {
                    el.style.viewTransitionName = 'none';
                });
                preview.style.viewTransitionName = vtName;
                requestAnimationFrame(() => {
                    location.href = link.href;
                });
                return;
            }

            if (!supportsNativeViewTransition) {
                storePreviewTransition(preview, link);
            }
        });
    }

    const homeHeroSection = document.getElementById('section1');
    const homeMarketing = homeHeroSection ? homeHeroSection.querySelector('[data-home-marketing]') : null;

    if (homeHeroSection && homeMarketing) {
        const prefersReducedMotion = window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches;

        const activateMarketing = () => {
            if (homeHeroSection.classList.contains('homeMarketingActive')) return;
            homeHeroSection.classList.add('homeMarketingActive');
            homeMarketing.setAttribute('aria-hidden', 'false');
        };

        if (prefersReducedMotion) {
            activateMarketing();
        } else {
            const parseTimePartMs = (part) => {
                const v = (part || '').trim();
                if (!v) return 0;
                if (v.endsWith('ms')) return Number.parseFloat(v) || 0;
                if (v.endsWith('s')) return (Number.parseFloat(v) || 0) * 1000;
                const n = Number.parseFloat(v);
                return Number.isFinite(n) ? n : 0;
            };

            const parseTimeListMs = (value) => {
                return String(value || '')
                    .split(',')
                    .map((p) => parseTimePartMs(p))
                    .reduce((max, ms) => Math.max(max, ms), 0);
            };

            const animatedEls = Array.from(homeHeroSection.querySelectorAll('.svg-animated-element'));
            let maxMs = 0;

            animatedEls.forEach((el) => {
                let styleTarget = el;
                if (el.tagName && el.tagName.toLowerCase() === 'foreignobject' && el.firstElementChild) {
                    styleTarget = el.firstElementChild;
                }
                const styles = getComputedStyle(styleTarget);
                const durationMs = parseTimeListMs(styles.animationDuration);
                const delayMs = parseTimeListMs(styles.animationDelay);
                maxMs = Math.max(maxMs, durationMs + delayMs);
            });

            const fixedDelayMs = 650;
            const totalMs = Math.min(Math.max(maxMs + fixedDelayMs, 900), 6000);
            setTimeout(activateMarketing, totalMs);
            setTimeout(activateMarketing, 6500);
        }
    }
});
